// ─── Table lookup ─────────────────────────────────────────────────────────────

function tableFor(metric: GrowthMetric, sex: Sex, standard: GrowthStandard): number[][] {
  if (standard === "WHO") {
    if (metric === "weight") return sex === "M" ? WHO_WEIGHT_M : WHO_WEIGHT_F;
    if (metric === "height") return sex === "M" ? WHO_HEIGHT_M : WHO_HEIGHT_F;
    if (metric === "head")   return sex === "M" ? WHO_HEAD_M   : WHO_HEAD_F;
  } else {
    if (metric === "weight") return sex === "M" ? CDC_WEIGHT_M : CDC_WEIGHT_F;
    if (metric === "height") return sex === "M" ? CDC_STATURE_M : CDC_STATURE_F;
    // No CDC head table
  }
  return [];
}

// ─── Public API ───────────────────────────────────────────────────────────────

export function getPercentileCurve(
  metric: GrowthMetric,
  sex: Sex,
  standard: GrowthStandard,
  mode: PercentileMode
): PercentilePoint[] {
  const table = tableFor(metric, sex, standard);
  return table.map(([month, p3, p15, p50, p85, p97]) => ({
    month,
    p3,
    p15: mode === 5 ? p15 : p50, // collapse to p50 when unused
    p50,
    p85: mode === 5 ? p85 : p50,
    p97,
  }));
}

export function interpolateAt(
  curve: PercentilePoint[],
  month: number
): PercentilePoint | null {
  if (!curve.length) return null;
  const exact = curve.find((p) => p.month === month);
  if (exact) return exact;
  const lo = [...curve].reverse().find((p) => p.month < month);
  const hi = curve.find((p) => p.month > month);
  if (!lo || !hi) return lo ?? hi ?? null;
  const t = (month - lo.month) / (hi.month - lo.month);
  const lerp = (a: number, b: number) => a + t * (b - a);
  return {
    month,
    p3: lerp(lo.p3, hi.p3),
    p15: lerp(lo.p15, hi.p15),
    p50: lerp(lo.p50, hi.p50),
    p85: lerp(lo.p85, hi.p85),
    p97: lerp(lo.p97, hi.p97),
  };
}
